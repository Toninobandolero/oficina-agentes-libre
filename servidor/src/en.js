// Lo fijo que escribe el propio servidor (líneas de actividad, títulos de tarjetas, errores que ve el panel), en el idioma del equipo.
// T`…` y T('…') lo buscan en EN si la oficina trabaja en inglés (perfil.idioma); si no, o si no está, sale en español tal cual.
// En las plantillas, ${…} se escribe {0}, {1}… (como en panel/en.js). Una prueba de sistema.test.js falla si algo marcado con T no tiene inglés.
// Úsalo dentro de las funciones, nunca al cargar el archivo: el idioma se mira al escribir. Lo que escriben los agentes no pasa por aquí.
import { leer } from './perfil.js';

export const enIngles = () => leer().idioma === 'en';
export const LOCALE = () => (enIngles() ? 'en-GB' : 'es-ES');
export function T(s, ...v) {
  const k = typeof s === 'string' ? s : s.reduce((a, x, i) => a + (i ? `{${i - 1}}` : '') + x, '');
  const t = (enIngles() && EN[k]) || k;
  return v.length ? t.replace(/\{(\d+)\}/g, (m, i) => (i < v.length ? v[i] : m)) : t;
}

